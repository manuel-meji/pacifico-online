CREATE TABLE estados_conciliacion (
    id_estado_conciliacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(200)
);

CREATE TABLE estados_revision_diferencia (
    id_estado_revision_diferencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(200)
);

CREATE TABLE tipos_diferencia (
    id_tipo_diferencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(200)
);

CREATE TABLE medios_pago (
    id_medio_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_medio VARCHAR(30) NOT NULL UNIQUE CHECK (nombre_medio IN ('tarjeta', 'sinpe', 'paypal'))
);

