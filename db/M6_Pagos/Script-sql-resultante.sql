-- 2. TABLA TRANSACCIONAL PRINCIPAL: PAGOS
CREATE TABLE pagos (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    id_cliente BIGINT NOT NULL,
    id_medio_pago BIGINT NOT NULL,
    id_estado_pago BIGINT NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    clave_idempotencia VARCHAR(100) NOT NULL UNIQUE,
    referencia_proveedor VARCHAR(100),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_confirmacion TIMESTAMPTZ,
    CONSTRAINT fk_pagos_medio FOREIGN KEY (id_medio_pago) REFERENCES medios_pago(id_medio_pago),
    CONSTRAINT fk_pagos_estado FOREIGN KEY (id_estado_pago) REFERENCES estados_pago(id_estado_pago)
);

-- 3. TABLA NOTIFICACIONES DE PAGO
CREATE TABLE notificaciones_pago (
    id_notificacion_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL,
    id_medio_pago BIGINT NOT NULL,
    id_estado_notificacion_pago BIGINT NOT NULL,
    referencia_proveedor VARCHAR(100) NOT NULL UNIQUE,
    fecha_recepcion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_notif_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago),
    CONSTRAINT fk_notif_medio FOREIGN KEY (id_medio_pago) REFERENCES medios_pago(id_medio_pago),
    CONSTRAINT fk_notif_estado FOREIGN KEY (id_estado_notificacion_pago) REFERENCES estados_notificacion_pago(id_estado_notificacion_pago)
);

-- 4. TABLA COMPROBANTES DE PAGO
CREATE TABLE comprobantes_pago (
    id_comprobante_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL UNIQUE,
    documento TEXT NOT NULL CHECK (length(trim(documento)) > 0),
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_comprobante_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago)
);

-- 5. TABLA FACTURAS ELECTRÓNICAS
CREATE TABLE facturas_electronicas (
    id_factura_electronica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_subpedido BIGINT NOT NULL,
    id_comercio BIGINT NOT NULL,
    id_pago BIGINT NOT NULL,
    id_cliente BIGINT NOT NULL,
    id_estado_factura_hacienda BIGINT NOT NULL,
    consecutivo VARCHAR(20) NOT NULL UNIQUE,
    xml_documento TEXT NOT NULL CHECK (length(trim(xml_documento)) > 0),
    monto_total NUMERIC(12,2) NOT NULL CHECK (monto_total > 0),
    razon_social_emisor VARCHAR(150) NOT NULL,
    cedula_juridica_emisor VARCHAR(20) NOT NULL,
    identificacion_receptor VARCHAR(20),
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_factura_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago),
    CONSTRAINT fk_factura_hacienda FOREIGN KEY (id_estado_factura_hacienda) REFERENCES estados_factura_hacienda(id_estado_factura_hacienda)
);

-- 6. TABLAS NOTAS DE CRÉDITO Y DÉBITO
CREATE TABLE notas_credito (
    id_nota_credito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura_electronica BIGINT NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    motivo VARCHAR(200) NOT NULL CHECK (length(trim(motivo)) > 0),
    xml_documento TEXT NOT NULL CHECK (length(trim(xml_documento)) > 0),
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_nc_factura FOREIGN KEY (id_factura_electronica) REFERENCES facturas_electronicas(id_factura_electronica)
);

CREATE TABLE notas_debito (
    id_nota_debito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura_electronica BIGINT NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    motivo VARCHAR(200) NOT NULL CHECK (length(trim(motivo)) > 0),
    xml_documento TEXT NOT NULL CHECK (length(trim(xml_documento)) > 0),
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_nd_factura FOREIGN KEY (id_factura_electronica) REFERENCES facturas_electronicas(id_factura_electronica)
);

-- 7. TABLA REEMBOLSOS
CREATE TABLE reembolsos (
    id_reembolso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL,
    id_subpedido BIGINT NULL,
    id_nota_credito BIGINT NULL UNIQUE,
    id_estado_reembolso BIGINT NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    motivo VARCHAR(200) NOT NULL CHECK (length(trim(motivo)) > 0),
    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_procesado TIMESTAMPTZ,
    CONSTRAINT fk_reembolso_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago),
    CONSTRAINT fk_reembolso_nc FOREIGN KEY (id_nota_credito) REFERENCES notas_credito(id_nota_credito),
    CONSTRAINT fk_reembolso_estado FOREIGN KEY (id_estado_reembolso) REFERENCES estados_reembolso(id_estado_reembolso)
);

-- 8. TABLAS CONCILIACIONES Y DIFERENCIAS
CREATE TABLE conciliaciones (
    id_conciliacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estado_conciliacion BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL CHECK (fecha_fin >= fecha_inicio),
    total_cobrado_sistema NUMERIC(14,2) NOT NULL CHECK (total_cobrado_sistema >= 0),
    total_reportado_pasarela NUMERIC(14,2) NOT NULL CHECK (total_reportado_pasarela >= 0),
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_conciliacion_estado FOREIGN KEY (id_estado_conciliacion) REFERENCES estados_conciliacion(id_estado_conciliacion)
);

CREATE TABLE diferencias_conciliacion (
    id_diferencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conciliacion BIGINT NOT NULL,
    id_pago BIGINT NOT NULL,
    id_tipo_diferencia BIGINT NOT NULL,
    id_estado_revision_diferencia BIGINT NOT NULL,
    monto_diferencia NUMERIC(12,2) NOT NULL CHECK (monto_diferencia <> 0),
    CONSTRAINT fk_dif_conciliacion FOREIGN KEY (id_conciliacion) REFERENCES conciliaciones(id_conciliacion),
    CONSTRAINT fk_dif_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago),
    CONSTRAINT fk_dif_tipo FOREIGN KEY (id_tipo_diferencia) REFERENCES tipos_diferencia(id_tipo_diferencia),
    CONSTRAINT fk_dif_revision FOREIGN KEY (id_estado_revision_diferencia) REFERENCES estados_revision_diferencia(id_estado_revision_diferencia)
);
